def _report_path(name: str) -> Path | None:
    artifact_dir = os.environ.get("HP2_ARTIFACT_DIR")
    return Path(artifact_dir) / name if artifact_dir else None


def write_report(
    name: str,
    *,
    status: str,
    invariant: str,
    reason_code: str | None = None,
    exit_reason: str = "",
    extra_artifacts: list[dict[str, str]] | None = None,
) -> Path | None:
    """Emit a report-schema-v1 JSON document; best-effort, never raises."""
    path = _report_path(name)
    if path is None:
        return None
    report: dict[str, object] = {
        "schema": 1,
        "name": path.stem,
        "status": status,
        "invariant": invariant,
        "data": {"profile": "data-none"},
        "artifacts": extra_artifacts or [],
        "command": "python3 Tests/SaveFormatTests.py",
        "exit_reason": exit_reason,
    }
    if reason_code is not None:
        report["reason_code"] = reason_code
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    except OSError:
        return None
    return path


def _discover_engine() -> Path | None:
    candidates: list[Path] = []
    explicit = os.environ.get("HP2_ENGINE_BINARY")
    if explicit:
        candidates.append(Path(explicit))
    bundle = REPOSITORY_ROOT / "dist" / "macos-arm64" / "HarryPotter2.app" / "Contents" / "MacOS"
    if bundle.is_dir():
        candidates.extend(sorted(entry for entry in bundle.iterdir() if entry.is_file()))
    for candidate in candidates:
        if candidate.is_file() and not candidate.is_symlink() and os.access(candidate, os.X_OK):
            return candidate
    return None


def _discover_data_root() -> Path | None:
    root = Path(os.environ.get("HP2_DATA_ROOT") or REPOSITORY_ROOT / "HarryPotter2" / "Unreal")
    required = ("System/Default.ini", "System/DefUser.ini")
    if all((root / relative).is_file() for relative in required):
        return root
    return None


