class SaveFormatContracts(unittest.TestCase):
    maxDiff = None

    @classmethod
    def setUpClass(cls) -> None:
        cls.manifest_path = FIXTURE_DIR / "MANIFEST.json"
        cls.manifest = json.loads(cls.manifest_path.read_text())
        cls.cases_by_file = {case["file"]: case for case in cls.manifest["cases"]}  # type: ignore[index]
        cls.bytes_by_file = {
            path.name: path.read_bytes()
            for path in sorted(FIXTURE_DIR.glob("*.usa"))
        }

    def _reader(self, name: str) -> p79.PackageReader:
        return p79.PackageReader(name, self.bytes_by_file[name])

    # -- corpus integrity ---------------------------------------------------

    def test_manifest_covers_exactly_the_committed_files(self) -> None:
        listed = {str(case["file"]) for case in self.manifest["cases"]}  # type: ignore[index]
        present = set(self.bytes_by_file)
        self.assertEqual(listed, present, "invariant save.corpus.manifest_covers_files")
        for case in self.manifest["cases"]:  # type: ignore[union-attr]
            data = self.bytes_by_file[str(case["file"])]
            self.assertEqual(
                hashlib.sha256(data).hexdigest(),
                case["sha256"],
                f"invariant save.corpus.fixture_sha256 for {case['file']}",
            )

    def test_corpus_regenerates_byte_identically(self) -> None:
        for name, (data, _layout) in build_corpus().items():
            self.assertEqual(
                data,
                self.bytes_by_file[name],
                f"invariant save.corpus.generator_matches_committed for {name}",
            )

    # -- golden behaviour ---------------------------------------------------

    def test_golden_saves_parse_with_literal_versioned_header(self) -> None:
        for name in GOLDEN_FILES:
            with self.subTest(file=name):
                case = self.cases_by_file[name]
                self.assertEqual(
                    case["expectation"], "parses_and_loads"
                )
                parsed = self._reader(name).read()
                summary = parsed["summary"]
                self.assertEqual(summary["tag"], 0x9E2A83C1, "invariant save.package79.header.tag")
                self.assertEqual(summary["version"], 79, "invariant save.package79.header.version")
                self.assertEqual(summary["licensee"], 0, "invariant save.package79.header.licensee")
                self.assertEqual(
                    summary["version_word"],
                    79,
                    "invariant save.package79.header.version_word_literal",
                )
                self.assertEqual(
                    parsed["package_name"],
                    Path(name).stem,
                    "invariant save.package79.package_name_from_stem",
                )
                self.assertTrue(parsed["exports"], "invariant save.package79.has_exports")

    def test_golden_filenames_satisfy_repair_save_slot_contract(self) -> None:
        for name in GOLDEN_FILES:
            self.assertIsNotNone(
                repair_save.SAVE_NAME.fullmatch(name),
                f"invariant save.slot.naming violated by {name}",
            )

    def test_save_slot_regex_accepts_only_canonical_slots(self) -> None:
        self.assertIsNone(repair_save.SAVE_NAME.fullmatch("checkpoint.usa"))
        self.assertIsNone(repair_save.SAVE_NAME.fullmatch("Save01.usa"))
        self.assertIsNone(repair_save.SAVE_NAME.fullmatch("SaveX.usa"))

    # -- corrupted variants -------------------------------------------------

    def test_corrupt_variants_rejected_with_precise_reasons(self) -> None:
        for case in self.manifest["cases"]:  # type: ignore[union-attr]
            if case["kind"] != "corrupt":
                continue
            with self.subTest(file=case["file"], reason_code=case["reason_code"]):
                reader = self._reader(str(case["file"]))
                with self.assertRaises(p79.PackageFormatError) as caught:
                    reader.read()
                message = str(caught.exception)
                self.assertIn(
                    str(case["message_contains"]),
                    message,
                    f"invariant {case['invariant']} violated with wrong diagnostic: {message}",
                )

    def test_payload_bit_flip_is_structurally_undetectable(self) -> None:
        """Documents the format's checksum blind spot (motivation for repair_save)."""
        pristine = self._reader("Save1.usa").read()
        flipped = self._reader("flipped_payload_bit.usa").read()
        self.assertNotEqual(
            pristine["exports"][0]["serial"]["sha256"],
            flipped["exports"][0]["serial"]["sha256"],
            "invariant save.package79.payload.flip_changes_content",
        )
        self.assertNotIn(
            "checksum",
            json.dumps(flipped).lower(),
            "invariant save.package79.payload.no_checksum_coverage",
        )

    # -- native writer roundtrip (opt-in) ------------------------------------

    @unittest.skipUnless(
        os.environ.get(ROUNDTRIP_ENV, "").lower() in ("1", "true", "yes"),
        f"native writer roundtrip is opt-in; set {ROUNDTRIP_ENV}=1",
    )
    def test_native_writer_roundtrip_matches_golden_structure(self) -> None:
        engine = _discover_engine()
        data_root = _discover_data_root()
        if engine is None or data_root is None:
            write_report(
                "save_format_roundtrip.json",
                status="blocked",
                invariant="save.native.writer_roundtrip",
                reason_code="engine.binary_or_data_unavailable",
                exit_reason=(
                    f"engine={engine!r} data_root={data_root!r}; set "
                    "HP2_ENGINE_BINARY / HP2_DATA_ROOT to override discovery"
                ),
            )
            self.skipTest("native engine binary or prototype data root unavailable")

        timeout = float(os.environ.get(ROUNDTRIP_TIMEOUT_ENV, "180"))
        with tempfile.TemporaryDirectory(prefix="hp2-saveformat-roundtrip-") as temporary:
            user_root = Path(temporary) / "User"
            (user_root / "Save").mkdir(parents=True)
            (user_root / "Game.ini").write_text("[Engine.Engine]\n")
            (user_root / "User.ini").write_text("[Engine.Input]\n")
            target = user_root / "Save" / "Save0.usa"
            shutil.copyfile(FIXTURE_DIR / "Save0.usa", target)
            try:
                repair_save.repair_save(engine, data_root, user_root, target, timeout_seconds=timeout)
            except repair_save.RepairError as exc:
                write_report(
                    "save_format_roundtrip.json",
                    status="blocked",
                    invariant="save.native.writer_roundtrip",
                    reason_code="save.engine_loader_rejected_synthetic_golden",
                    exit_reason=f"repair_save failed: {exc}",
                )
                self.skipTest(f"native loader rejected the synthetic golden: {exc}")

            native = p79.PackageReader("Save0.usa", target.read_bytes()).read()

        golden = p79.PackageReader("Save0.usa", (FIXTURE_DIR / "Save0.usa").read_bytes()).read()
        self.assertEqual(native["summary"]["tag"], 0x9E2A83C1, "invariant save.package79.header.tag")
        self.assertEqual(native["summary"]["version"], 79, "invariant save.package79.header.version")
        self.assertEqual(native["summary"]["licensee"], 0, "invariant save.package79.header.licensee")
        self.assertEqual(
            sorted(native["summary"]),
            sorted(golden["summary"]),
            "invariant save.native.summary_shape_matches_golden",
        )
        self.assertEqual(
            sorted(native["regions"]),
            sorted(golden["regions"]),
            "invariant save.native.region_shape_matches_golden",
        )


def _generate() -> int:
    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    corpus = build_corpus()
    for name, (data, _layout) in sorted(corpus.items()):
        (FIXTURE_DIR / name).write_bytes(data)
    (FIXTURE_DIR / "MANIFEST.json").write_text(
        json.dumps(build_manifest(), indent=2, sort_keys=True) + "\n"
    )
    print(f"wrote {len(corpus)} archives + MANIFEST.json to {FIXTURE_DIR}")
    return 0


def main(argv: list[str] | None = None) -> int:
    arguments = sys.argv[1:] if argv is None else argv
    if "--generate" in arguments:
        return _generate()

    suite = unittest.defaultTestLoader.loadTestsFromModule(sys.modules[__name__])
    result = unittest.TextTestRunner(verbosity=2).run(suite)
    status = "pass" if result.wasSuccessful() else "fail"
    write_report(
        "save_format_tests.json",
        status=status,
        invariant="save.format.golden_corpus",
        exit_reason=(
            f"run={result.testsRun} failures={len(result.failures)} "
            f"errors={len(result.errors)} skipped={len(result.skipped)}"
        ),
    )
    return 0 if result.wasSuccessful() else 1


if __name__ == "__main__":
    raise SystemExit(main())
