FIXTURE_DIR = REPOSITORY_ROOT / "Tests" / "Fixtures" / "save-format-golden"

# Literal versioned-header contract shared with the native loader
# (PackageAudit.cpp / UnPackage.cpp) and package79_reference.
PACKAGE_TAG = p79.PACKAGE_TAG
PACKAGE_VERSION = p79.PACKAGE_VERSION
LICENSEE_VERSION = p79.LICENSEE_VERSION
VERSION_WORD = PACKAGE_VERSION | (LICENSEE_VERSION << 16)

# Synthetic placeholder values; the package-79 reader does not constrain them.
SYNTHETIC_NAME_FLAGS = 0x07001000
SYNTHETIC_OBJECT_FLAGS = 0x001C0001  # public + load-for-client/server/edit shape
FIXED_GUID = (0x2144F1A6, 0x8C7D4B2E, 0x9A51C03D, 0x6E2F8B17)

HEADER_SIZE = 64  # 56-byte summary + one 8-byte generation record

# Generic UE1 class/package identifiers; no game-data content.
_SAVE_NAMES = ("Core", "Package", "Engine", "Class", "Level", "PersistentLevel")
_SAVE_IMPORTS = (
    ("Core", "Package", 0, "Engine"),  # Core.Package Engine
    ("Engine", "Class", -1, "Level"),  # Engine.Class Level (class of the export)
)
_LEVEL_EXPORT = {
    "class_ref": -2,  # -> Engine.Class Level import above
    "super_ref": 0,
    "outer_ref": 0,  # rooted at the package itself
    "name": "PersistentLevel",
}


def _synthetic_payload(size: int = 96) -> bytes:
    """Deterministic stand-in for serialized actor data."""
    return bytes((index * 37 + 11) & 0xFF for index in range(size))


def _name_record(text: str, *, utf16: bool) -> bytes:
    if utf16:
        units = len(text) + 1
        return (
            p79.encode_compact_index(-units)
            + text.encode("utf-16-le")
            + b"\0\0"
            + struct.pack("<I", SYNTHETIC_NAME_FLAGS)
        )
    encoded = text.encode("latin-1")
    return (
        p79.encode_compact_index(len(encoded) + 1)
        + encoded
        + b"\0"
        + struct.pack("<I", SYNTHETIC_NAME_FLAGS)
    )


def _import_record(
    name_index: dict[str, int],
    class_package: str,
    class_name: str,
    outer_ref: int,
    object_name: str,
) -> bytes:
    record = p79.encode_compact_index(name_index[class_package])
    record += p79.encode_compact_index(name_index[class_name])
    record += struct.pack("<i", outer_ref)
    record += p79.encode_compact_index(name_index[object_name])
    return record


def _export_record(
    name_index: dict[str, int], spec: dict[str, object], serial_offset: int | None
) -> bytes:
    payload = spec.get("payload", b"")
    assert isinstance(payload, bytes)
    record = p79.encode_compact_index(int(spec["class_ref"]))  # type: ignore[arg-type]
    record += p79.encode_compact_index(int(spec["super_ref"]))  # type: ignore[arg-type]
    record += struct.pack("<i", int(spec["outer_ref"]))  # type: ignore[arg-type]
    record += p79.encode_compact_index(name_index[str(spec["name"])])
    record += struct.pack("<I", SYNTHETIC_OBJECT_FLAGS)
    record += p79.encode_compact_index(len(payload))
    if payload:
        assert serial_offset is not None
        record += p79.encode_compact_index(serial_offset)
    return record


def build_package(
    stem: str,
    names: tuple[str, ...],
    *,
    imports: tuple[tuple[str, str, int, str], ...] = (),
    export_specs: tuple[dict[str, object], ...] = (),
    utf16_names: bool = False,
) -> tuple[bytes, dict[str, object]]:
    """Assemble one minimal well-formed package-79 archive.

    Layout follows the order the reader enforces:
    summary(+generations) | name table | serial payloads | imports | exports.
    """
    name_index = {text: index for index, text in enumerate(names)}
    name_blob = b"".join(_name_record(text, utf16=utf16_names) for text in names)
    names_end = HEADER_SIZE + len(name_blob)

    payload_chunks: list[bytes] = []
    payload_spans: list[tuple[int, int]] = []
    export_records: list[bytes] = []
    cursor = names_end
    for spec in export_specs:
        payload = spec.get("payload", b"")
        assert isinstance(payload, bytes)
        serial_offset = cursor if payload else None
        export_records.append(_export_record(name_index, spec, serial_offset))
        if payload:
            payload_chunks.append(payload)
            payload_spans.append((cursor, cursor + len(payload)))
            cursor += len(payload)
    import_offset = cursor

    import_records = [_import_record(name_index, *entry) for entry in imports]
    import_blob = b"".join(import_records)
    # Absolute file offsets of each import's outer_ref i32 (records vary in width).
    import_outer_offsets: list[int] = []
    walk = import_offset
    for entry, record in zip(imports, import_records):
        prefix = p79.encode_compact_index(name_index[entry[0]])
        prefix += p79.encode_compact_index(name_index[entry[1]])
        import_outer_offsets.append(walk + len(prefix))
        walk += len(record)
    export_offset = import_offset + len(import_blob)

    summary = struct.pack(
        "<IIIiiiiii4Ii2i",
        PACKAGE_TAG,
        VERSION_WORD,
        0,  # package flags
        len(names),
        HEADER_SIZE,  # name_offset: names begin immediately after the summary
        len(export_specs),
        export_offset,
        len(imports),
        import_offset,
        *FIXED_GUID,
        1,  # generation count
        len(export_specs),  # latest generation: export count
        len(names),  # latest generation: name count
    )
    data = bytes(summary) + name_blob + b"".join(payload_chunks) + import_blob
    data += b"".join(export_records)
    layout: dict[str, object] = {
        "stem": stem,
        "magic_offset": 0,
        "version_word_offset": 4,
        "name_count_offset": 12,
        "payload_spans": payload_spans,
        "import_outer_refs": import_outer_offsets,
        "file_size": len(data),
    }
    return data, layout


def _patch_i32(data: bytes, offset: int, value: int) -> bytes:
    patched = bytearray(data)
    struct.pack_into("<i", patched, offset, value)
    return bytes(patched)


def build_corpus() -> dict[str, tuple[bytes, dict[str, object] | None]]:
    """Deterministic golden + corrupted corpus; committed fixtures derive from this."""
    corpus: dict[str, tuple[bytes, dict[str, object] | None]] = {}

    minimal, minimal_layout = build_package(
        "Save0",
        _SAVE_NAMES,
        imports=_SAVE_IMPORTS,
        export_specs=(_LEVEL_EXPORT,),
    )
    corpus["Save0.usa"] = (minimal, minimal_layout)

    payload_spec = {**_LEVEL_EXPORT, "payload": _synthetic_payload()}
    with_payload, payload_layout = build_package(
        "Save1",
        _SAVE_NAMES,
        imports=_SAVE_IMPORTS,
        export_specs=(payload_spec,),
    )
    corpus["Save1.usa"] = (with_payload, payload_layout)

    utf16, _utf16_layout = build_package(
        "Save2",
        _SAVE_NAMES,
        imports=_SAVE_IMPORTS,
        export_specs=(_LEVEL_EXPORT,),
        utf16_names=True,
    )
    corpus["Save2.usa"] = (utf16, None)

    def mutate(base: bytes, mutate_fn) -> bytes:
        return mutate_fn(bytearray(base))

    # Header surgery on Save0.
    corpus["bad_magic.usa"] = (
        mutate(minimal, lambda b: struct.pack_into("<I", b, 0, 0xDEADBEEF) or bytes(b)),
        None,
    )
    corpus["bad_version.usa"] = (
        mutate(minimal, lambda b: struct.pack_into("<I", b, 4, 80) or bytes(b)),
        None,
    )
    corpus["bad_licensee.usa"] = (
        mutate(
            minimal,
            lambda b: struct.pack_into("<I", b, 4, PACKAGE_VERSION | (1 << 16)) or bytes(b),
        ),
        None,
    )
    corpus["zeroed_name_count.usa"] = (
        mutate(minimal, lambda b: struct.pack_into("<i", b, 12, 0) or bytes(b)),
        None,
    )

    # Reference surgery on Save1 (its import table carries two records).
    outer_at = int(payload_layout["import_outer_refs"][1])  # type: ignore[index]
    corpus["dangling_import_outer.usa"] = (
        _patch_i32(with_payload, outer_at, 99999),
        {"patched_offset": outer_at},
    )

    # Structural damage.
    corpus["truncated_tail.usa"] = (with_payload[:-8], {"removed_bytes": 8})
    corpus["empty.usa"] = (b"", {})

    # Silent corruption probe: flip one payload bit; package-79 has no checksum,
    # so the structural reader cannot notice. repair_save exists precisely
    # because of this blind spot.
    span = payload_layout["payload_spans"][0]  # type: ignore[index]
    flip_at = int(span[0] + (span[1] - span[0]) // 2)  # type: ignore[index]
    flipped = mutate(with_payload, lambda b: b.__setitem__(flip_at, b[flip_at] ^ 0x08) or bytes(b))
    corpus["flipped_payload_bit.usa"] = (flipped, {"flipped_offset": flip_at})

    return corpus


