def build_manifest() -> dict[str, object]:
    corpus = build_corpus()
    cases: list[dict[str, object]] = []
    labels = {"layer": "integration", "data_profile": "data-none"}
    for name in GOLDEN_FILES:
        data, _layout = corpus[name]
        cases.append(
            {
                "file": name,
                "kind": "golden",
                "package_stem": Path(name).stem,
                "expectation": "parses_and_loads",
                "invariant": "save.package79.golden_parses",
                "sha256": hashlib.sha256(data).hexdigest(),
                "size": len(data),
                "labels": labels,
            }
        )
    for case in CORRUPTION_CASES:
        data, _layout = corpus[str(case["file"])]
        cases.append(
            {
                **case,
                "kind": "corrupt",
                "expectation": "rejected",
                "sha256": hashlib.sha256(data).hexdigest(),
                "size": len(data),
                "labels": labels,
            }
        )
    data, layout = corpus[PROBE_CASE["file"]]
    cases.append(
        {
            **PROBE_CASE,
            "kind": "probe",
            "expectation": "parses_structurally_corruption_undetectable",
            "detail": (
                "package-79 carries no checksum; the structural reader accepts "
                "this file. Only the export payload sha256 changes, which is why "
                "repair_save re-saves through the native loader instead of "
                "patching bytes."
            ),
            "flipped_offset": layout["flipped_offset"] if layout else None,  # type: ignore[index]
            "sha256": hashlib.sha256(data).hexdigest(),
            "size": len(data),
            "labels": labels,
        }
    )
    return {
        "schema_version": 1,
        "format": "hp2-save-format-golden",
        "generator": "Tests/SaveFormatTests.py",
        "regenerate_command": "python3 Tests/SaveFormatTests.py --generate",
        "package_tag_hex": f"0x{PACKAGE_TAG:08x}",
        "package_version": PACKAGE_VERSION,
        "licensee_version": LICENSEE_VERSION,
        "data_profile": "data-none",
        "notes": [
            "Synthetic corpus: generic UE1 identifiers, arithmetic payloads, "
            "fixed GUIDs. No copyrighted game data.",
            "package-79 has no checksum field anywhere in the format; see the "
            "flipped_payload_bit.usa probe case.",
        ],
        "cases": cases,
    }


