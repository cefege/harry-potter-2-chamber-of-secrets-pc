#!/usr/bin/env python3
"""Save-format golden-corpus contracts for HP2 `.usa` saves (UE1 package v79).

Build/repair_save.py never parses save bytes itself: it stages an isolated
profile and drives the native Unreal loader/writer (`UGameEngine::SaveGame`,
`UnGame.cpp`) over them. This suite exercises the same format through the two
refactor-free module seams the repository already ships:

* ``repair_save``         -- slot-naming contract (``SAVE_NAME``) and, behind
                             an opt-in gate, the real native save writer.
* ``package79_reference`` -- the canonical Python reader of the exact
                             package-79 layout the native loader enforces
                             (tag 0x9E2A83C1, version 79, licensee 0).

The corpus under Tests/Fixtures/save-format-golden/ is generated by
:func:`build_corpus` below and must stay byte-identical to it; MANIFEST.json
is the executable specification every test iterates.

Everything here is deterministic: fixed GUIDs, synthetic arithmetic payloads,
no network, no wall clock, locale-independent byte parsing.
"""

