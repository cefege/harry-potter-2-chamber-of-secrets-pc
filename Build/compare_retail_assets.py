#!/usr/bin/env python3
"""Deterministically compare an extracted HP2 prototype tree with a retail tree."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import struct
import sys
from collections import Counter, defaultdict
from pathlib import Path, PurePosixPath
from typing import Any, Iterable, NoReturn

PACKAGE_TAG = 0x9E2A83C1
CHUNK_SIZE = 1024 * 1024
CANONICAL_ROOTS = {
    "maps": "Maps",
    "music": "Music",
    "sounds": "Sounds",
    "textures": "Textures",
    "system": "System",
    "help": "Help",
}
PACKAGE_EXTENSIONS = {
    ".u": "script_package",
    ".unr": "map_package",
    ".utx": "texture_package",
    ".uax": "sound_package",
}
WINDOWS_BINARY_EXTENSIONS = {".com", ".dll", ".drv", ".exe", ".lib", ".ocx", ".sys"}
WINDOWS_SCRIPT_EXTENSIONS = {".bat", ".cmd"}
LOCALIZATION_EXTENSIONS = {
    ".cht",
    ".det",
    ".est",
    ".frt",
    ".gre",
    ".int",
    ".itt",
    ".jpt",
    ".kor",
    ".pol",
    ".ptt",
    ".rut",
    ".sch",
    ".spa",
    ".sve",
    ".tai",
}
SOURCE_EXTENSIONS = {
    ".asm",
    ".bas",
    ".c",
    ".cc",
    ".cls",
    ".cpp",
    ".cxx",
    ".def",
    ".frm",
    ".h",
    ".hh",
    ".hpp",
    ".inc",
    ".inl",
    ".rc",
    ".uc",
}
PROJECT_EXTENSIONS = {
    ".cmake",
    ".dsp",
    ".dsw",
    ".mak",
    ".ncb",
    ".opt",
    ".plg",
    ".sln",
    ".vbp",
    ".vbw",
    ".vcproj",
}
IMAGE_EXTENSIONS = {".bmp", ".dds", ".gif", ".ico", ".jpeg", ".jpg", ".pcx", ".png", ".tga"}
AUDIO_EXTENSIONS = {".aif", ".aiff", ".flac", ".mp3", ".ogg", ".wav", ".xa"}
FONT_EXTENSIONS = {".fon", ".otf", ".ttc", ".ttf"}
CONFIG_EXTENSIONS = {".cfg", ".conf", ".ini"}
DOCUMENT_EXTENSIONS = {".doc", ".htm", ".html", ".pdf", ".rtf", ".txt"}
ARCHIVE_EXTENSIONS = {".7z", ".cab", ".gz", ".rar", ".tar", ".zip"}
CLASSIFICATIONS = ("identical", "retail_only", "prototype_only", "changed")


class ComparisonError(RuntimeError):
    """An input tree cannot be inventoried without losing information."""


def error(message: str) -> NoReturn:
    raise ComparisonError(message)


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prototype-root", required=True, type=Path, help="prototype Unreal tree")
    parser.add_argument("--retail-root", required=True, type=Path, help="retail installation tree")
    destination = parser.add_mutually_exclusive_group(required=True)
    destination.add_argument("--output", type=Path, help="write the generated JSON report")
    destination.add_argument("--check", type=Path, help="compare generated bytes with an existing report")
    return parser.parse_args(argv)


def validate_root(path: Path, label: str) -> Path:
    try:
        resolved = path.expanduser().resolve(strict=True)
    except OSError as exc:
        error(f"{label} root {path}: {exc}")
    if not resolved.is_dir():
        error(f"{label} root is not a directory: {resolved}")
    return resolved


def iter_files(root: Path) -> Iterable[tuple[str, Path]]:
    """Yield regular files in byte-stable relative-path order without following links."""
    found: list[tuple[str, Path]] = []
    for current, directory_names, file_names in os.walk(root, followlinks=False):
        directory_names.sort(key=lambda value: (value.casefold(), value))
        file_names.sort(key=lambda value: (value.casefold(), value))
        current_path = Path(current)
        for name in file_names:
            path = current_path / name
            relative = path.relative_to(root).as_posix()
            if path.is_symlink():
                error(f"symbolic link is not a regular tree file: {root / relative}")
            if not path.is_file():
                error(f"unsupported non-regular tree entry: {root / relative}")
            found.append((relative, path))
    yield from sorted(found, key=lambda item: (item[0].casefold(), item[0]))


def normalize_path(relative: str, side: str) -> tuple[str, list[str]]:
    parts = list(PurePosixPath(relative).parts)
    if not parts:
        error(f"empty relative path in {side} inventory")
    notes: list[str] = []
    canonical_root = CANONICAL_ROOTS.get(parts[0].casefold())
    if canonical_root is not None:
        if parts[0] != canonical_root:
            notes.append(f"canonicalized_root:{parts[0]}->{canonical_root}")
        parts[0] = canonical_root

    # Some retail distributions contain both help/X and help/help/X.  Treat the
    # second help component as a duplicated root while retaining the source path.
    if side == "retail" and parts[0] == "Help" and len(parts) > 1 and parts[1].casefold() == "help":
        removed = parts.pop(1)
        notes.append(f"collapsed_duplicate_help_root:{removed}")
    return "/".join(parts), notes


def hash_and_probe(path: Path) -> tuple[int, str, dict[str, int | str] | None, bool]:
    digest = hashlib.sha256()
    first = b""
    size = 0
    try:
        with path.open("rb") as stream:
            while True:
                chunk = stream.read(CHUNK_SIZE)
                if not chunk:
                    break
                if len(first) < 8:
                    first += chunk[: 8 - len(first)]
                size += len(chunk)
                digest.update(chunk)
    except OSError as exc:
        error(f"cannot read {path}: {exc}")

    package_header = None
    if len(first) >= 8:
        tag, version_word = struct.unpack_from("<II", first)
        if tag == PACKAGE_TAG:
            package_header = {
                "licensee_version": (version_word >> 16) & 0xFFFF,
                "package_version": version_word & 0xFFFF,
                "tag": f"0x{tag:08x}",
                "version_word": version_word,
            }
    return size, digest.hexdigest(), package_header, first.startswith(b"MZ")


def category_for(normalized_path: str, extension: str, package_header: dict[str, Any] | None) -> str:
    root = normalized_path.split("/", 1)[0]
    if package_header is not None:
        if extension in PACKAGE_EXTENSIONS:
            return PACKAGE_EXTENSIONS[extension]
        if root == "Maps":
            return "map_package"
        if root == "Textures":
            return "texture_package"
        if root == "Sounds":
            return "sound_package"
        return "ue1_package"
    if extension in WINDOWS_BINARY_EXTENSIONS:
        return "windows_binary"
    if extension in WINDOWS_SCRIPT_EXTENSIONS:
        return "windows_script"
    if extension in LOCALIZATION_EXTENSIONS:
        return "localization"
    if extension in CONFIG_EXTENSIONS:
        return "configuration"
    if extension in AUDIO_EXTENSIONS:
        return "music" if root == "Music" or extension == ".ogg" else "audio"
    if extension in IMAGE_EXTENSIONS:
        return "image"
    if extension in FONT_EXTENSIONS:
        return "font"
    if extension in SOURCE_EXTENSIONS:
        return "source_code"
    if extension in PROJECT_EXTENSIONS:
        return "build_project"
    if extension in DOCUMENT_EXTENSIONS:
        return "documentation"
    if extension in ARCHIVE_EXTENSIONS:
        return "archive"
    if extension == ".scc" or PurePosixPath(normalized_path).name.casefold() in {"mssccprj.scc", "vssver.scc"}:
        return "source_control_metadata"
    if root == "Help":
        return "help_asset"
    return "other"


def inventory(root: Path, side: str) -> list[dict[str, Any]]:
    entries: list[dict[str, Any]] = []
    for relative, path in iter_files(root):
        normalized, normalizations = normalize_path(relative, side)
        extension = PurePosixPath(normalized).suffix.casefold()
        size, sha256, package_header, is_mz = hash_and_probe(path)
        windows_binary = extension in WINDOWS_BINARY_EXTENSIONS or is_mz
        entry: dict[str, Any] = {
            "category": category_for(normalized, extension, package_header),
            "extension": extension,
            "normalizations": normalizations,
            "normalized_relative_path": normalized,
            "package_header": package_header,
            "portability": "nonportable_windows_binary" if windows_binary else "not_flagged",
            "relative_path": relative,
            "sha256": sha256,
            "size": size,
        }
        if windows_binary:
            reasons = []
            if extension in WINDOWS_BINARY_EXTENSIONS:
                reasons.append(f"windows_binary_extension:{extension}")
            if is_mz:
                reasons.append("mz_executable_header")
            entry["nonportable_reasons"] = reasons
        entries.append(entry)
    return entries


def group_inventory(entries: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for entry in entries:
        grouped[entry["normalized_relative_path"].casefold()].append(entry)
    for values in grouped.values():
        values.sort(key=lambda item: (item["relative_path"].casefold(), item["relative_path"]))
    return dict(grouped)


def assign_file_classifications(
    prototype: list[dict[str, Any]], retail: list[dict[str, Any]]
) -> str:
    """Classify each physical file with deterministic one-to-one matching."""
    prototype_by_signature: dict[tuple[int, str], list[dict[str, Any]]] = defaultdict(list)
    retail_by_signature: dict[tuple[int, str], list[dict[str, Any]]] = defaultdict(list)
    for entry in prototype:
        prototype_by_signature[(entry["size"], entry["sha256"])].append(entry)
    for entry in retail:
        retail_by_signature[(entry["size"], entry["sha256"])].append(entry)

    for signature in sorted(set(prototype_by_signature) | set(retail_by_signature)):
        prototype_matches = prototype_by_signature.get(signature, [])
        retail_matches = retail_by_signature.get(signature, [])
        matched = min(len(prototype_matches), len(retail_matches))
        for entry in prototype_matches[:matched] + retail_matches[:matched]:
            entry["classification"] = "identical"

    unmatched_prototype = [entry for entry in prototype if "classification" not in entry]
    unmatched_retail = [entry for entry in retail if "classification" not in entry]
    changed = min(len(unmatched_prototype), len(unmatched_retail))
    for entry in unmatched_prototype[:changed] + unmatched_retail[:changed]:
        entry["classification"] = "changed"
    for entry in unmatched_prototype[changed:]:
        entry["classification"] = "prototype_only"
    for entry in unmatched_retail[changed:]:
        entry["classification"] = "retail_only"

    if not prototype:
        return "retail_only"
    if not retail:
        return "prototype_only"
    if all(entry["classification"] == "identical" for entry in prototype + retail):
        return "identical"
    return "changed"


def collision_reason(entries: list[dict[str, Any]]) -> list[str]:
    reasons: list[str] = []
    normalized_paths = {entry["normalized_relative_path"] for entry in entries}
    if len(normalized_paths) > 1:
        reasons.append("filename_case_collision")
    if any(
        any(note.startswith("collapsed_duplicate_help_root:") for note in entry["normalizations"])
        for entry in entries
    ):
        reasons.append("duplicate_help_root_alias")
    if len({entry["relative_path"] for entry in entries}) > 1 and not reasons:
        reasons.append("normalized_path_collision")
    return reasons


def summarize_side(entries: list[dict[str, Any]]) -> dict[str, Any]:
    category_counts = Counter(entry["category"] for entry in entries)
    category_bytes: Counter[str] = Counter()
    portability_counts = Counter(entry["portability"] for entry in entries)
    package_versions = Counter(
        f"{entry['package_header']['package_version']}/{entry['package_header']['licensee_version']}"
        for entry in entries
        if entry["package_header"] is not None
    )
    for entry in entries:
        category_bytes[entry["category"]] += entry["size"]
    return {
        "bytes": sum(entry["size"] for entry in entries),
        "categories": {
            category: {"bytes": category_bytes[category], "files": count}
            for category, count in sorted(category_counts.items())
        },
        "files": len(entries),
        "package_versions": dict(sorted(package_versions.items())),
        "portability": dict(sorted(portability_counts.items())),
    }


def summarize_file_category_classifications(
    entries: list[dict[str, Any]],
) -> dict[str, dict[str, int]]:
    counts: dict[str, Counter[str]] = defaultdict(Counter)
    for entry in entries:
        counts[entry["category"]][entry["classification"]] += 1
    return {
        category: {name: category_counts[name] for name in CLASSIFICATIONS}
        for category, category_counts in sorted(counts.items())
    }


def build_report(prototype_root: Path, retail_root: Path) -> dict[str, Any]:
    prototype_entries = inventory(prototype_root, "prototype")
    retail_entries = inventory(retail_root, "retail")
    prototype_groups = group_inventory(prototype_entries)
    retail_groups = group_inventory(retail_entries)
    all_keys = sorted(set(prototype_groups) | set(retail_groups))

    records: list[dict[str, Any]] = []
    collisions: dict[str, list[dict[str, Any]]] = {"prototype": [], "retail": []}
    logical_classifications: Counter[str] = Counter()
    prototype_file_classifications: Counter[str] = Counter()
    retail_file_classifications: Counter[str] = Counter()
    category_classifications: dict[str, Counter[str]] = defaultdict(Counter)

    for key in all_keys:
        prototype = prototype_groups.get(key, [])
        retail = retail_groups.get(key, [])
        classification = assign_file_classifications(prototype, retail)
        candidates = prototype or retail
        display_path = min(
            (entry["normalized_relative_path"] for entry in candidates),
            key=lambda value: (value.casefold(), value),
        )
        extensions = sorted({entry["extension"] for entry in prototype + retail})
        categories = sorted({entry["category"] for entry in prototype + retail})
        category = categories[0] if len(categories) == 1 else "mixed"
        record = {
            "categories": categories,
            "category": category,
            "classification": classification,
            "extensions": extensions,
            "logical_path": display_path,
            "logical_path_casefold": key,
            "prototype": prototype,
            "retail": retail,
        }
        records.append(record)
        logical_classifications[classification] += 1
        prototype_file_classifications.update(entry["classification"] for entry in prototype)
        retail_file_classifications.update(entry["classification"] for entry in retail)
        category_classifications[category][classification] += 1

        for side, entries in (("prototype", prototype), ("retail", retail)):
            if len(entries) > 1:
                collisions[side].append(
                    {
                        "logical_path": display_path,
                        "logical_path_casefold": key,
                        "reasons": collision_reason(entries),
                        "source_paths": [entry["relative_path"] for entry in entries],
                    }
                )

    classification_summary = {
        "logical_paths": {name: logical_classifications[name] for name in CLASSIFICATIONS},
        "prototype_files": {name: prototype_file_classifications[name] for name in CLASSIFICATIONS},
        "retail_files": {name: retail_file_classifications[name] for name in CLASSIFICATIONS},
    }
    if sum(classification_summary["logical_paths"].values()) != len(records):
        error("internal error: logical-path classifications do not reconcile")
    if sum(classification_summary["prototype_files"].values()) != len(prototype_entries):
        error("internal error: prototype file classifications do not reconcile")
    if sum(classification_summary["retail_files"].values()) != len(retail_entries):
        error("internal error: retail file classifications do not reconcile")

    return {
        "category_classification_summary": {
            category: {name: counts[name] for name in CLASSIFICATIONS}
            for category, counts in sorted(category_classifications.items())
        },
        "classification_summary": classification_summary,
        "file_category_classification_summary": {
            "prototype": summarize_file_category_classifications(prototype_entries),
            "retail": summarize_file_category_classifications(retail_entries),
        },
        "collisions": collisions,
        "format": "hp2-retail-parity",
        "inventories": {
            "prototype": summarize_side(prototype_entries),
            "retail": summarize_side(retail_entries),
        },
        "logical_path_count": len(records),
        "paths": records,
        "roots": {
            "prototype": str(prototype_root),
            "retail": str(retail_root),
        },
        "schema_version": 1,
    }


def serialize(report: dict[str, Any]) -> bytes:
    return (json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8")


def write_output(path: Path, data: bytes) -> None:
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(f".{path.name}.tmp")
        temporary.write_bytes(data)
        os.replace(temporary, path)
    except OSError as exc:
        error(f"cannot write report {path}: {exc}")


def check_output(path: Path, data: bytes) -> None:
    try:
        existing = path.read_bytes()
    except OSError as exc:
        error(f"cannot read check report {path}: {exc}")
    if existing != data:
        error(f"report is out of date: {path}")


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        prototype_root = validate_root(args.prototype_root, "prototype")
        retail_root = validate_root(args.retail_root, "retail")
        data = serialize(build_report(prototype_root, retail_root))
        if args.output is not None:
            write_output(args.output, data)
            print(f"wrote {args.output} ({len(data)} bytes)")
        else:
            check_output(args.check, data)
            print(f"report is current: {args.check}")
        return 0
    except ComparisonError as exc:
        print(f"compare_retail_assets.py: error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
