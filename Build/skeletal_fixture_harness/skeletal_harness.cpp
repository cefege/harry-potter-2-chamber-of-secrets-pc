/*
 * Bit-exact replay harness for the ORIGINAL HarryPotter2 UnSkeletalMesh.cpp
 * (pinned ref 32dcfda). Built and run by Build/skeletal_fixture_harness/gen_skeletal.sh.
 *
 * Usage: skeletal_harness <family>
 *   math       FAnimVec::Init, FAnimVec(FQuat), FAnimVec::Quat, FAnimVec::Vector
 *   trig       GMath.TrigFLOAT[0..NUM_ANGLES) as produced by the real FGlobalMath ctor
 *   apply_anim ApplyAnim (tracks, root-only, tween, aux anims with transient/loop
 *              flags, DestroyActor on aux removal), observed via GetBoneCoords
 *   frame      GetFrame (plain, weapon bone, DisplayBones/DisplayInfluences,
 *              bAnimByOwner, LOD clamp and out-of-range vertex-index break)
 *   root       GetRootMovement, AdjustRootMovement, AnimCycleMovement
 *   bounds     GetRenderBoundingBox, GetCollisionBoundingBox, GetMeshCoords,
 *              MeshAdjust, SetScale, FlipFaces, BoneIndex, BoneName
 *
 * Output: one line per case, whitespace separated. Floats are printed as
 * 0x%08x of their IEEE bit pattern; integers in decimal. No addresses, times
 * or host-dependent values are printed. PRNG: xorshift64*, fixed seed per
 * family (kSeed ^ family index), so two runs are byte-identical.
 *
 * Object model:
 *   - USkeletalMesh, UAnimation: placement-new through their REAL constructors
 *     (so the real vtables are emitted by the compiled TU). The out-of-line
 *     UObject() and UMesh() constructors live in Core/Engine TUs that are not
 *     compiled, so the harness provides empty bodies (the object is zeroed
 *     first, which is the state those constructors leave for these fields).
 *   - AActor: zeroed storage, no constructor (AActor has virtual methods only
 *     through UObject; none are called on actors here).
 *   - ULevel: zeroed storage whose first word points at a harness vtable
 *     (g_vt) holding a single recording hook for ULevel::DestroyActor.
 *   - FName: harness defines FName::Names (kNameCount calloc'd FNameEntry records,
 *     the real table lives in UnName.cpp which is not linked) and HardcodedNames.
 *     Ported code compares only FName::Index, so names are FName((EName)i).
 *   - GMalloc, GLog, GError, GNull, GMath, GCache: defined here. GMath and
 *     GCache use the real FGlobalMath and FMemCache code (UnMath.cpp, UnCache.cpp).
 *   - Unreached out-of-line functions link to stubs that print the symbol name
 *     and abort (generated by gen_skeletal.sh).
 *
 * Coverage gaps (C++ branches not reached by this harness):
 *   - USkeletalMesh::GetBones: declared private, no definition in 32dcfda.
 *   - USkeletalMesh::Serialize, UAnimation::Serialize, ULodMesh/UMesh paths:
 *     archive I/O, not part of the ported surface.
 *   - ApplyAnim: ParentHdr != NULL branch (only called with NULL here);
 *     missing-link warning path is reached only when BoneIndices is -1 for a
 *     bone that is not the default-pose case (warning text is discarded).
 *   - GetFrame: pivot/influence debug output is driven only in frame Variant 2
 *     (DisplayBones and DisplayInfluences); the debugf text itself is discarded.
 *   - GetRootMovement: the same debugf output discard applies.
 *   - ANIM48 is defined unconditionally in Engine/Inc/UnSkeletalMesh.h:21, so the
 *     SWORD-key, BASE_SCALE and sinf/asinf branches are the ones compiled and
 *     replayed. The non-ANIM48 FAnimVec layout is not compiled.
 *   - Logf/debugf text is discarded (FOutputDevice::Logf lives in UnMisc.cpp,
 *     not linked). appError/appErrorf also live in UnMisc.cpp, so reaching one
 *     hits the generated unreached: stub, which prints the symbol and aborts.
 */

