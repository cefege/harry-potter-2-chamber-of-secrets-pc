static void print_destroyed( AActor** Aux, int N )
{
	for( int a = 0; a < N; ++a )
	{
		int Hit = 0;
		for( int d = 0; d < g_ndestroyed; ++d )
			if( g_destroyed[d] == Aux[a] )
				Hit = 1;
		pi( Hit );
	}
}

