struct HarnessMalloc : FMalloc
{
	void* Malloc( DWORD Count, const TCHAR* Tag ) { return calloc( 1, Count ? Count : 1 ); }
	void* Realloc( void* Original, DWORD Count, const TCHAR* Tag )
	{
		// Zero fresh and grown memory: TArray::Add leaves unset fields otherwise, and
		// heap garbage would make fixture output run-dependent.
		size_t N = Count ? Count : 1;
		if( !Original )
			return calloc( 1, N );
		size_t Old = malloc_size( Original );
		void* P = realloc( Original, N );
		if( P && N > Old )
			memset( (BYTE*)P + Old, 0, N - Old );
		return P;
	}
	void Free( void* Original ) { free( Original ); }
	void DumpAllocs() {}
	void HeapCheck() {}
	void Init() {}
	void Exit() {}
};

