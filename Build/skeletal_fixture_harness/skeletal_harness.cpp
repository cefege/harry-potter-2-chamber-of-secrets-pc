// Mesh block: scalar header, then RefSkeleton, Points, BoneWeightIdx, BoneWeights,
// LocalPoints, Faces, BoundingBoxes, and DefaultAnimation presence.
static void put_mesh( USkeletalMesh* M )
{
	pi( M->FrameVerts ); pi( M->WeaponBoneIndex ); pi( M->SkeletalDepth );
	pv( M->Origin ); pi( M->RotOrigin.Pitch ); pi( M->RotOrigin.Yaw ); pi( M->RotOrigin.Roll );
	pv( M->Scale ); pb( M->BoundingBox );
	pf( M->BoundingSphere.X ); pf( M->BoundingSphere.Y ); pf( M->BoundingSphere.Z ); pf( M->BoundingSphere.W );
	pc( M->WeaponAdjust ); pc( M->ClassicWeaponCoords );
	pi( M->DisplayBones ); pi( M->DisplayInfluences );
	pi( M->RefSkeleton.Num() );
	for( int B = 0; B < M->RefSkeleton.Num(); ++B )
	{
		FMeshBone& Bn = M->RefSkeleton( B );
		pn( Bn.Name ); pi( Bn.Flags ); pi( Bn.ParentIndex ); pi( Bn.NumChildren ); pi( Bn.Depth );
		pv( Bn.BonePos.Place.Pos ); pq( Bn.BonePos.Place.Quat );
		pf( Bn.BonePos.Length ); pf( Bn.BonePos.XSize ); pf( Bn.BonePos.YSize ); pf( Bn.BonePos.ZSize );
	}
	pi( M->Points.Num() );
	for( int V = 0; V < M->Points.Num(); ++V )
		pv( M->Points( V ) );
	pi( M->BoneWeightIdx.Num() );
	for( int B = 0; B < M->BoneWeightIdx.Num(); ++B )
	{
		pi( M->BoneWeightIdx( B ).WeightIndex ); pi( M->BoneWeightIdx( B ).Number );
	}
	pi( M->BoneWeights.Num() );
	for( int J = 0; J < M->BoneWeights.Num(); ++J )
	{
		pi( M->BoneWeights( J ).PointIndex ); pi( M->BoneWeights( J ).BoneWeight );
	}
	pi( M->LocalPoints.Num() );
	for( int J = 0; J < M->LocalPoints.Num(); ++J )
		pv( M->LocalPoints( J ) );
	pi( M->Faces.Num() );
	for( int F = 0; F < M->Faces.Num(); ++F )
	{
		pi( M->Faces( F ).iWedge[0] ); pi( M->Faces( F ).iWedge[1] ); pi( M->Faces( F ).iWedge[2] );
	}
	pi( M->BoundingBoxes.Num() );
	for( int s = 0; s < M->BoundingBoxes.Num(); ++s )
		pb( M->BoundingBoxes( s ) );
	pi( M->DefaultAnimation != NULL );
}

// Anim block: RefBones, AnimSeqs, then each Move with its tracks and keys.
static void put_anim( UAnimation* A )
{
	pi( A->RefBones.Num() );
	for( int B = 0; B < A->RefBones.Num(); ++B )
	{
		pn( A->RefBones( B ).Name ); pi( A->RefBones( B ).Flags ); pi( A->RefBones( B ).ParentIndex );
	}
	pi( A->AnimSeqs.Num() );
	for( int S = 0; S < A->AnimSeqs.Num(); ++S )
	{
		FMeshAnimSeq& Seq = A->AnimSeqs( S );
		pn( Seq.Name ); pn( Seq.Group ); pi( Seq.StartFrame ); pi( Seq.NumFrames ); pf( Seq.Rate );
	}
	pi( A->Moves.Num() );
	for( int S = 0; S < A->Moves.Num(); ++S )
	{
		MotionChunk& Mv = A->Moves( S );
		pv( Mv.RootSpeed3D ); pf( Mv.TrackTime ); pi( Mv.StartBone ); pi( Mv.Flags );
		pi( Mv.BoneIndices.Num() );
		for( int i = 0; i < Mv.BoneIndices.Num(); ++i )
			pi( Mv.BoneIndices( i ) );
		pi( Mv.AnimTracks.Num() );
		for( int T = 0; T < Mv.AnimTracks.Num(); ++T )
		{
			FAnalogTrack& Tr = Mv.AnimTracks( T );
			int K = Tr.KeyQuat.Num();
			pi( Tr.Flags ); pf( Tr.PosScale ); pf( Tr.TimeScale ); pi( K );
			for( int k = 0; k < K; ++k )
			{
				pi( Tr.KeyQuat( k ).X ); pi( Tr.KeyQuat( k ).Y ); pi( Tr.KeyQuat( k ).Z );
			}
			for( int k = 0; k < K; ++k )
			{
				pi( Tr.KeyPos( k ).X ); pi( Tr.KeyPos( k ).Y ); pi( Tr.KeyPos( k ).Z );
			}
			for( int k = 0; k < K; ++k )
				pi( Tr.KeyDelta( k ) );
		}
	}
}

// Actor block: every field new_actor/new_aux sets, plus Owner and Mesh presence.
// The owner is serialized as a flag; the replay links it to the preceding actor block.
static void put_actor( AActor* O )
{
	pn( O->AnimSequence ); pf( O->AnimFrame ); pf( O->AnimRate ); pf( O->AnimLast );
	pf( O->TweenRate ); pf( O->TweenAlpha ); pi( O->AnimBone );
	pi( O->bAnimLoop ); pi( O->bAnimMove ); pi( O->bAnimTransient ); pi( O->bAnimByOwner );
	pi( O->Physics ); pi( O->bAlignBottom ); pi( O->bCollideWorld ); pi( O->CollideType );
	pf( O->CollisionHeight ); pf( O->DrawScale ); pi( O->Wideness );
	pv( O->PrePivot ); pf( O->SavedPrePivotZ ); pv( O->Location );
	pi( O->Rotation.Pitch ); pi( O->Rotation.Yaw ); pi( O->Rotation.Roll );
	pi( O->Owner != NULL );
	pi( O->Mesh != NULL );
}

static void run_math( int Case )
{
	flush_case();
	FVector V = rvec( -1.5f, 1.5f );
	float Inv = frand( 0.25f, 4.f );
	FAnimVec A;
	A.Init( V, Inv );
	FQuat Q = rquat();
	FAnimVec B( Q );
	FQuat R = B.Quat();
	float S = frand( 0.5f, 2.f );
	FVector W = B.Vector( S );
	printf( "%d", Case );
	pv( V ); pf( Inv ); pi( A.X ); pi( A.Y ); pi( A.Z );
	pq( Q ); pi( B.X ); pi( B.Y ); pi( B.Z );
	pq( R ); pf( S ); pv( W );
	printf( "\n" );
}

static void run_trig()
{
	for( int i = 0; i < FGlobalMath::NUM_ANGLES; ++i )
		printf( "%d 0x%08x\n", i, fbits( GMath.TrigFLOAT[i] ) );
}

static void run_apply( int Case )
{
	flush_case();
	int NB = 1 + irand( 6 );
	int NS = 1 + irand( 3 );
	USkeletalMesh* M = new_mesh( NB, 4 + irand( 8 ), 1 );
	UAnimation* A = new_anim( M, NS );
	M->DefaultAnimation = irand( 2 ) ? A : NULL;
	int SeqPick = irand( NS + 1 );
	AActor* O = new_actor( A, SeqPick, NS );
	int NAux = irand( 3 );
	AActor* Aux[4];
	for( int a = 0; a < NAux; ++a )
	{
		Aux[a] = new_aux( A, irand( NS ), NS );
		O->AuxAnims.Add( 1 );
		O->AuxAnims( O->AuxAnims.Num() - 1 ) = Aux[a];
	}
	int RootOnly = irand( 2 );
	printf( "%d", Case );
	put_mesh( M ); put_anim( A ); put_actor( O );
	pi( NAux );
	for( int a = 0; a < NAux; ++a )
		put_actor( Aux[a] );
	pi( RootOnly );
	g_ndestroyed = 0;
	M->ApplyAnim( O, NULL, RootOnly != 0 );
	pf( O->AnimFrame ); pf( O->AnimLast ); pf( O->TweenAlpha );
	pi( O->AuxAnims.Num() );
	print_destroyed( Aux, NAux );
	for( int b = 0; b < NB; ++b )
		pc( M->GetBoneCoords( O, b ) );
	printf( "\n" );
}

static void run_frame( int Case )
{
	flush_case();
	int NB = 1 + irand( 6 );
	int NV = 4 + irand( 21 );
	int NS = 1 + irand( 3 );
	USkeletalMesh* M = new_mesh( NB, NV, 2 + irand( 4 ) );
	UAnimation* A = new_anim( M, NS );
	int Variant = Case % 4;
	if( Variant == 1 )
		M->WeaponBoneIndex = irand( NB );
	if( Variant == 2 )
	{
		M->DisplayBones = 1;
		M->DisplayInfluences = 1;
	}
	AActor* Parent = new_actor( A, 0, NS );
	AActor* O = new_actor( A, irand( NS ), NS );
	O->Owner = Parent;
	O->bAnimByOwner = Variant == 3;
	FCoords C = rcoords();
	int Lod = ( Case >> 1 ) % 2 == 0 ? NV : 1 + irand( NV );
	int Stride = (Case & 1) ? 16 : (int)sizeof(FVector);
	FVector* Verts = (FVector*)calloc( NV, Stride );
	// Sentinel NaN in every slot: GetFrame must write exactly VertexNum entries.
	for( int v = 0; v < NV; ++v )
		for( int c = 0; c < 3; ++c )
			*(DWORD*)((BYTE*)Verts + v * Stride + c * 4) = 0x7FC0BEEF;
	printf( "%d", Case );
	put_mesh( M ); put_anim( A ); put_actor( Parent ); put_actor( O );
	pc( C ); pi( NV ); pi( Lod ); pi( Stride );
	M->GetFrame( Verts, Stride, C, O, Lod );
	pi( Lod );
	for( int v = 0; v < NV; ++v )
		pv( *(FVector*)((BYTE*)Verts + v * Stride) );
	if( M->DisplayBones || M->DisplayInfluences )
	{
		pi( M->DebugPivots.Num() );
		for( int p = 0; p < M->DebugPivots.Num(); ++p )
			pv( M->DebugPivots( p ) );
		pi( M->DebugParents.Num() );
		for( int p = 0; p < M->DebugParents.Num(); ++p )
			pi( M->DebugParents( p ) );
		pi( M->DebugVerts.Num() );
	}
	printf( "\n" );
}

static void run_root( int Case )
{
	flush_case();
	int NB = 1 + irand( 6 );
	int NS = 1 + irand( 3 );
	USkeletalMesh* M = new_mesh( NB, 4 + irand( 8 ), 1 );
	UAnimation* A = new_anim( M, NS );
	AActor* O = new_actor( A, irand( NS ), NS );
	FVector Adj = rvec( -16.f, 16.f );
	printf( "%d", Case );
	put_mesh( M ); put_anim( A ); put_actor( O ); pv( Adj );
	FVector R1 = M->GetRootMovement( O );
	pv( R1 );
	M->AdjustRootMovement( O, Adj );
	FVector R2 = M->GetRootMovement( O );
	pv( R2 );
	FVector Cyc = M->AnimCycleMovement( O );
	pv( Cyc );
	printf( "\n" );
}

static void run_bounds( int Case )
{
	flush_case();
	int NB = 1 + irand( 6 );
	int NS = 1 + irand( 3 );
	USkeletalMesh* M = new_mesh( NB, 4 + irand( 8 ), 1 + irand( 4 ) );
	UAnimation* A = new_anim( M, NS );
	AActor* O = new_actor( A, irand( NS ), NS );
	O->Mesh = M;
	M->BoundingBoxes.Add( NS );
	for( int s = 0; s < NS; ++s )
	{
		FBox& Bx = M->BoundingBoxes( s );
		Bx.Min = rvec( -64.f, 0.f );
		Bx.Max = rvec( 0.f, 64.f );
		Bx.IsValid = 1;
	}
	UBOOL Exact = irand( 2 );
	UBOOL World = irand( 2 );
	FVector NewScale = rvec( 0.25f, 4.f );
	int Want = irand( NB + 2 ) + 1;
	printf( "%d", Case );
	put_mesh( M ); put_anim( A ); put_actor( O );
	pi( Exact ); pi( World ); pv( NewScale ); pi( Want );
	pc( M->GetRenderBoundingBox( O, Exact ) );
	pb( M->GetCollisionBoundingBox( O, World ) );
	pc( M->GetMeshCoords( O ) );
	pv( M->MeshAdjust( O ) );
	M->SetScale( NewScale );
	pv( M->Scale );
	pf( M->MeshScaleMax );
	M->FlipFaces();
	for( int f = 0; f < M->Faces.Num(); ++f )
	{
		pi( M->Faces( f ).iWedge[0] );
		pi( M->Faces( f ).iWedge[1] );
		pi( M->Faces( f ).iWedge[2] );
	}
	pi( M->BoneIndex( FName( (EName)Want ) ) );
	for( int b = 0; b < NB; ++b )
		pi( M->BoneName( b ).GetIndex() );
	printf( "\n" );
}

int main( int argc, char** argv )
{
	if( argc < 2 )
	{
		fprintf( stderr, "usage: skeletal_harness <math|trig|apply_anim|frame|root|bounds>\n" );
		return 2;
	}
	init_names();
	g_rng = kSeed;
	GCache.Init( 32 << 20, 4096 );
	install_level();

	const char* Family = argv[1];
	if( !strcmp( Family, "math" ) )
	{
		for( int c = 0; c < kCasesMath; ++c )
			run_math( c );
	}
	else if( !strcmp( Family, "trig" ) )
		run_trig();
	else if( !strcmp( Family, "apply_anim" ) )
	{
		for( int c = 0; c < kCasesApply; ++c )
			run_apply( c );
	}
	else if( !strcmp( Family, "frame" ) )
	{
		for( int c = 0; c < kCasesFrame; ++c )
			run_frame( c );
	}
	else if( !strcmp( Family, "root" ) )
	{
		for( int c = 0; c < kCasesRoot; ++c )
			run_root( c );
	}
	else if( !strcmp( Family, "bounds" ) )
	{
		for( int c = 0; c < kCasesBounds; ++c )
			run_bounds( c );
	}
	else
	{
		fprintf( stderr, "unknown family: %s\n", Family );
		return 2;
	}
	return 0;
}
