static const uint64_t kSeed = 0x5E1E7A4B0C0FFEE5ULL;
static uint64_t g_rng;

static uint64_t rnext()
{
	uint64_t X = g_rng;
	X ^= X >> 12;
	X ^= X << 25;
	X ^= X >> 27;
	g_rng = X;
	return X * 0x2545F4914F6CDD1DULL;
}

static float frand( float Lo, float Hi )
{
	return Lo + (Hi - Lo) * (float)((rnext() >> 40) * (1.0 / 16777216.0));
}

static int irand( int N )
{
	return (int)(rnext() % (uint64_t)N);
}

static FVector rvec( float Lo, float Hi )
{
	float X = frand( Lo, Hi );
	float Y = frand( Lo, Hi );
	float Z = frand( Lo, Hi );
	return FVector( X, Y, Z );
}

static FQuat rquat()
{
	float X = frand( -1.f, 1.f );
	float Y = frand( -1.f, 1.f );
	float Z = frand( -1.f, 1.f );
	float W = frand( -1.f, 1.f );
	return FQuat( X, Y, Z, W );
}

static FCoords rcoords()
{
	FCoords C;
	C.Origin = rvec( -256.f, 256.f );
	C.XAxis = rvec( -1.f, 1.f );
	C.YAxis = rvec( -1.f, 1.f );
	C.ZAxis = rvec( -1.f, 1.f );
	return C;
}

static uint32_t fbits( float F )
{
	uint32_t U;
	memcpy( &U, &F, sizeof U );
	return U;
}

static void pf( float F ) { printf( " 0x%08x", fbits( F ) ); }
static void pi( long long I ) { printf( " %lld", I ); }
static void pv( const FVector& V ) { pf( V.X ); pf( V.Y ); pf( V.Z ); }
static void pq( const FQuat& Q ) { pf( Q.X ); pf( Q.Y ); pf( Q.Z ); pf( Q.W ); }
static void pc( const FCoords& C ) { pv( C.Origin ); pv( C.XAxis ); pv( C.YAxis ); pv( C.ZAxis ); }
static void pb( const FBox& B ) { pv( B.Min ); pv( B.Max ); pi( B.IsValid ); }

