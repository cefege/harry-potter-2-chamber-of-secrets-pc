static UBOOL hook_destroy( ULevel* Self, AActor* Actor, UBOOL bNetForce )
{
	if( g_ndestroyed < 64 )
		g_destroyed[g_ndestroyed++] = Actor;
	return 1;
}

static void install_level()
{
	auto PmDestroy = &ULevel::DestroyActor;
	g_vt[vt_slot( &PmDestroy )] = (void*)&hook_destroy;
	g_level = (ULevel*)calloc( 1, sizeof(ULevel) );
	void** Vt = g_vt;
	memcpy( (void*)g_level, &Vt, sizeof Vt );
}

